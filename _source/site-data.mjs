// Writes ../site/data.js (video list, chapters, lengths) and ../thumbs/*.jpg
// for the tutorial site. Chapter times use the same timing rules as build.mjs,
// measured from the narration clips in assets/<slug>/vo-*.wav.
//
//   node site-data.mjs

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const HERE = path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, "$1");
const ROOT = path.resolve(HERE, "..");
const FF =
  "C:/Users/ryanc/AppData/Local/Microsoft/WinGet/Packages/Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe/ffmpeg-9.1-full_build/bin";
const MIN_INTRO = 3.0;
const MIN_STEP = 4.5;

const secs = (file) =>
  parseFloat(
    execFileSync(`${FF}/ffprobe.exe`, ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file], {
      encoding: "utf8",
    }).trim(),
  );

// Which audience shelf each video sits on.
const shelf = (who) => {
  const w = who.toLowerCase();
  if (w.includes("every")) return "employee";
  if (w.includes("manager")) return "manager";
  return "admin";
};

const features = JSON.parse(fs.readFileSync(path.join(HERE, "features.json"), "utf8"));
fs.mkdirSync(path.join(ROOT, "thumbs"), { recursive: true });
fs.mkdirSync(path.join(ROOT, "site"), { recursive: true });

const videos = features.map((f, i) => {
  const nn = String(i + 1).padStart(2, "0");
  const file = `${nn}-${f.slug}.mp4`;
  const adir = path.join(HERE, "assets", f.slug);
  const intro = Math.max(MIN_INTRO, secs(path.join(adir, "vo-00.wav")) + 0.9);
  let t = intro;
  const chapters = [{ t: 0, title: "Introduction" }];
  f.steps.forEach((s, j) => {
    chapters.push({ t: Math.round(t * 10) / 10, title: s.caption, detail: s.detail || "" });
    t += Math.max(MIN_STEP, secs(path.join(adir, `vo-${String(j + 1).padStart(2, "0")}.wav`)) + 1.1);
  });
  chapters.push({ t: Math.round(t * 10) / 10, title: "Wrap-up" });

  const thumb = `thumbs/${nn}-${f.slug}.jpg`;
  // Thumbnail: the first step, once its screen and caption have settled in.
  execFileSync(`${FF}/ffmpeg.exe`, [
    "-v", "error", "-y", "-ss", String(intro + 1.2), "-i", path.join(ROOT, file),
    "-frames:v", "1", "-vf", "scale=640:-1", "-q:v", "4", path.join(ROOT, thumb),
  ]);

  return {
    n: i + 1,
    slug: f.slug,
    file,
    thumb,
    title: f.title,
    subtitle: f.subtitle || "",
    who: f.who || "",
    shelf: shelf(f.who || ""),
    steps: f.steps.length,
    duration: Math.round(secs(path.join(ROOT, file))),
    chapters,
  };
});

fs.writeFileSync(
  path.join(ROOT, "site", "data.js"),
  "// Generated by _source/site-data.mjs. Do not edit by hand.\nwindow.PAYLALO_VIDEOS = " +
    JSON.stringify(videos, null, 2) +
    ";\n",
);
console.log(`Wrote site/data.js and ${videos.length} thumbnails.`);
